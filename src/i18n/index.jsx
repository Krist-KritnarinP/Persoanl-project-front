const LangContext = createContext({
  lang: "th",
  setLang: () => {},
  t: (k) => k,
  locale: "th-TH",
});

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem("lang");
      return saved && dict[saved] ? saved : "th";
    } catch {
      return "th";
    }
  });

  useEffect(() => {
    try {
      localStorage.setItem("lang", lang);
    } catch {
      // ignore
    }
    document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  }, [lang]);

  const value = useMemo(() => {
    const t = (key, values = {}) =>
      (dict[lang]?.[key] ?? dict.th[key] ?? key).replace(
        /\{(\w+)\}/g,
        (match, name) => values[name] ?? match,
      );
    return { lang, setLang: setLangState, t, locale: LOCALES[lang] || "th-TH" };
  }, [lang]);

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}

/**
 * Non-hook translator for places without React context (e.g. zustand stores).
 * Reads the saved language directly. Same fallback + {var} support as t().
 */
export function tKey(key, values = {}) {
  let lang = "th";
  try {
    lang = localStorage.getItem("lang") || "th";
  } catch {
    // ignore
  }
  const table = dict[lang] ?? dict.th;
  return (table[key] ?? dict.th[key] ?? key).replace(
    /\{(\w+)\}/g,
    (match, name) => values[name] ?? match,
  );
}
